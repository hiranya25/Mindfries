import { redirect } from "next/navigation";
import { PageHeader } from "@/components/ui";
import { listReportsForCompany } from "@/lib/db";
import { getCurrentSession } from "@/lib/session";
import { ReportsTable } from "@/components/ReportsTable";

export const dynamic = "force-dynamic";

export default async function ReportsPage() {
  const session = await getCurrentSession();
  if (!session) redirect("/login");

  const reports = await listReportsForCompany(session.company.id);

  return (
    <div className="space-y-8">
      <PageHeader eyebrow={session.company.name} title="Reports">
        Per-candidate evidence and evaluation — generated by the candidate workspace&apos;s evaluation pipeline once a
        session is submitted.
      </PageHeader>

      {reports.length === 0 ? (
        <div className="hair-card p-10 text-center">
          <div className="mx-auto mb-4 grid h-12 w-12 place-items-center rounded-full bg-accent-soft text-accent">◉</div>
          <h2 className="text-lg font-extrabold tracking-tight">No sessions yet</h2>
          <p className="mx-auto mt-2 max-w-md text-sm text-dim">
            Reports appear here once an invited candidate starts a session in the workspace.
          </p>
        </div>
      ) : (
        <ReportsTable reports={reports} />
      )}
    </div>
  );
}
